"""Hard-Only (HO) baseline (SOAR paper §4.3): fail@128 train only, no synthetic data.

Same training objective as `baselines.promotion_question` (TRL GRPO + LoRA with
the identical reward, prompt, callback, and hyperparameters), but trained on
`fail@128 train` ALONE — the `promotion_questions.jsonl` / `D_best` synthetic
data generated by a SOAR run is intentionally excluded. After training, evaluate
the final LoRA on the fail@128 test split via `eval.py` (pass@k with
k ∈ {1,4,8,16,32}, 32 samples @ T=1.0 — Table 3), and emit a result JSON that
`visualize/pass_at_k.py` picks up with an HO legend entry.

CLI:
    accelerate launch --num_processes 1 -m baselines.hard_only \\
        --out-dir <training-dir> --fail128-dir <fail128> \\
        --base-model <hf-id> --lr 1e-05 --seed 0
"""

